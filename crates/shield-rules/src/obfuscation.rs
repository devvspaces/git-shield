//! T13: obfuscated or hidden code in source files, plus the correlation that
//! ties a suspicious file to a config entry that executes it.

use crate::util::{added_lines, clip, texts};
use regex::Regex;
use shield_core::{Detector, FileChange, Finding, ScanContext, Severity, Threat};
use std::collections::HashSet;
use std::sync::LazyLock;

const SOURCE_EXT: &[&str] = &[
    "js", "mjs", "cjs", "ts", "mts", "cts", "jsx", "tsx", "py", "sh", "bash", "zsh", "ps1", "rb", "php", "pl", "vue",
    "svelte",
];
const SKIP_DIRS: &[&str] =
    &["dist", "build", "vendor", "node_modules", "third_party", "third-party", ".next", "out", "coverage"];
const OFFSCREEN_GAP: usize = 150;
const LONG_LINE: usize = 5000;
const SECRET_LEN: usize = 200;
const ENTROPY_MIN: f64 = 5.2;

/// Code, then a long run of blanks, then more code: content pushed out of view.
static OFFSCREEN: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(&format!(r"(^|\S)[ \t]{{{OFFSCREEN_GAP},}}\S")).unwrap());
static EXEC_FN: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"\b(eval|Function|exec|execSync|spawn|spawnSync|compile|os\.system|os\.popen|subprocess\.\w+|runInNewContext|runInThisContext|Invoke-Expression|iex)\s*\(|\brequire\(\s*['\x22]child_process['\x22]\s*\)").unwrap()
});
static DECODE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r#"(?i)\batob\s*\(|Buffer\.from\([^)]*,\s*['"](base64|hex)['"]|b64decode|base64\.(b64)?decode|fromCharCode|zlib\.decompress|marshal\.loads|codecs\.decode|bytes\.fromhex|unhexlify|FromBase64String|(\\x[0-9a-f]{2}){16,}"#).unwrap()
});
static LONG_STRING: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(&format!(r#"["'`]([A-Za-z0-9+/=_\-]{{{SECRET_LEN},}})["'`]"#)).unwrap());

fn in_scope(c: &FileChange) -> bool {
    let p = c.path.to_ascii_lowercase();
    let name = p.rsplit('/').next().unwrap_or(&p);
    if name.contains(".min.") || name.ends_with(".map") || name.ends_with(".d.ts") {
        return false;
    }
    if p.split('/').any(|seg| SKIP_DIRS.contains(&seg)) {
        return false;
    }
    c.extension_lower().is_some_and(|e| SOURCE_EXT.contains(&e.as_str()))
}

fn generated(text: &str) -> bool {
    text.lines().take(5).any(|l| {
        let l = l.to_ascii_lowercase();
        l.contains("@generated")
            || l.contains("do not edit")
            || l.contains("auto-generated")
            || l.contains("generated by")
    })
}

fn entropy(s: &str) -> f64 {
    let mut counts = [0u32; 256];
    for b in s.bytes() {
        counts[b as usize] += 1;
    }
    let n = s.len() as f64;
    counts
        .iter()
        .filter(|&&c| c > 0)
        .map(|&c| {
            let p = f64::from(c) / n;
            -p * p.log2()
        })
        .sum()
}

pub struct Obfuscation;

impl Detector for Obfuscation {
    fn name(&self) -> &'static str {
        "obfuscation"
    }

    fn interested(&self, c: &FileChange) -> bool {
        c.new.as_ref().is_some_and(|b| !b.symlink) && in_scope(c)
    }

    fn scan_file(&self, c: &FileChange, out: &mut Vec<Finding>) {
        let (Some((old, new)), Some(blob)) = (texts(c), c.new.as_ref()) else { return };
        if generated(&new) {
            return;
        }
        let added: HashSet<&str> = added_lines(&old, &new).into_iter().collect();
        if added.is_empty() {
            return;
        }
        let lines: Vec<&str> = new.lines().collect();
        let oid = &blob.oid;
        let is_added = |i: usize| added.contains(lines[i]);

        if let Some(i) = (0..lines.len()).find(|&i| is_added(i) && OFFSCREEN.is_match(lines[i])) {
            let l = lines[i];
            let hidden = l.trim_start();
            let gap_end = hidden
                .find(|ch: char| ch.is_whitespace())
                .map_or(0, |s| hidden[s..].find(|ch: char| !ch.is_whitespace()).map_or(0, |e| s + e));
            out.push(
                Finding::new(
                    Threat::T13,
                    "t13.hidden-offscreen",
                    Severity::High,
                    "Code hidden far to the right of a line",
                )
                .anchor(format!("{oid}:offscreen"))
                .detail(format!(
                    "line {}: {} … [{} blanks] … {}",
                    i + 1,
                    clip(hidden[..gap_end.min(hidden.len())].trim_end(), 60),
                    OFFSCREEN_GAP,
                    clip(hidden[gap_end..].trim(), 160)
                ))
                .detail("Editors and diff views wrap or cut long lines; this pushes code out of view."),
            );
        }

        let pair = (0..lines.len()).find(|&i| {
            is_added(i) && {
                let here = EXEC_FN.is_match(lines[i]) && DECODE.is_match(lines[i]);
                let next = lines.get(i + 1).is_some_and(|n| {
                    (EXEC_FN.is_match(lines[i]) && DECODE.is_match(n))
                        || (DECODE.is_match(lines[i]) && EXEC_FN.is_match(n))
                });
                here || next
            }
        });
        if let Some(i) = pair {
            out.push(
                Finding::new(Threat::T13, "t13.decode-exec", Severity::High, "Code decodes data and executes it")
                    .anchor(format!("{oid}:decode-exec"))
                    .detail(format!("line {}: {}", i + 1, clip(lines[i].trim(), 200)))
                    .detail(
                        "Decode-then-execute (base64/hex/char codes into eval/exec/a shell) hides what actually runs.",
                    ),
            );
        }

        if let Some(i) = (0..lines.len()).find(|&i| is_added(i) && lines[i].len() > LONG_LINE) {
            out.push(
                Finding::new(Threat::T13, "t13.long-line", Severity::Medium, "Very long line in a source file")
                    .anchor(format!("{oid}:long-line"))
                    .detail(format!("line {} is {} characters: {}", i + 1, lines[i].len(), clip(lines[i].trim(), 120))),
            );
        }

        let blob_str = (0..lines.len()).filter(|&i| is_added(i)).find_map(|i| {
            LONG_STRING.captures_iter(lines[i]).find_map(|c| {
                let s = c.get(1)?.as_str();
                let e = entropy(s);
                (e >= ENTROPY_MIN).then_some((i, s.len(), e))
            })
        });
        if let Some((i, len, e)) = blob_str {
            out.push(
                Finding::new(Threat::T13, "t13.high-entropy", Severity::Medium, "Long random-looking string literal")
                    .anchor(format!("{oid}:entropy"))
                    .detail(format!(
                        "line {}: {len} characters, entropy {e:.1} bits/char (encoded or encrypted data)",
                        i + 1
                    )),
            );
        }
    }
}

/// Context step: a new exec entry (task, hook, script, server…) that runs a
/// file flagged as obfuscated or disguised.
pub struct PayloadWired;

impl Detector for PayloadWired {
    fn name(&self) -> &'static str {
        "payload-wired"
    }

    fn scan_context(&self, _ctx: &ScanContext, out: &mut Vec<Finding>) {
        let suspicious: Vec<(String, String)> = out
            .iter()
            .filter(|f| !f.transited && matches!(f.threat, Threat::T13 | Threat::T2) && f.severity >= Severity::Medium)
            .filter_map(|f| Some((f.path.clone()?, f.title.clone())))
            .collect();
        if suspicious.is_empty() {
            return;
        }
        let mut wired = Vec::new();
        for f in out.iter().filter(|f| !f.transited && !f.refs.is_empty()) {
            let dir = f.path.as_deref().and_then(|p| p.rsplit_once('/')).map(|(d, _)| d);
            for r in &f.refs {
                let candidates = [Some(r.clone()), dir.map(|d| format!("{d}/{r}"))];
                let Some((path, why)) = suspicious.iter().find(|(p, _)| candidates.iter().flatten().any(|c| c == p))
                else {
                    continue;
                };
                let mut w = Finding::new(
                    Threat::T13,
                    "t13.payload-wired",
                    Severity::Critical,
                    format!("`{}` executes `{path}`, which is flagged as a payload", f.path.as_deref().unwrap_or("?")),
                )
                .path(path.clone())
                .anchor(format!("{}->{path}", f.path.as_deref().unwrap_or("")))
                .detail(format!("runner: {} ({})", f.title, f.rule))
                .detail(format!("target: {why}"));
                if let Some(cm) = &f.commit {
                    w = w.commit(cm.clone());
                }
                wired.push(w);
            }
        }
        out.extend(wired);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testutil::{added, modified, scan};

    #[test]
    fn offscreen_payload() {
        let js = format!("module.exports = {{ content: [] }};{}eval(require('fs'));\n", " ".repeat(200));
        let f = scan(&Obfuscation, &added("tailwind.config.js", js.as_bytes()));
        assert_eq!(f[0].rule, "t13.hidden-offscreen");
        assert_eq!(f[0].severity, Severity::High);
        // Indentation alone is not hiding.
        let ok = format!("{}const x = 1;\n", " ".repeat(8));
        assert!(scan(&Obfuscation, &added("a.js", ok.as_bytes())).is_empty());
    }

    #[test]
    fn decode_exec() {
        let py = "import base64\nexec(base64.b64decode('cHJpbnQoMSk='))\n";
        assert_eq!(scan(&Obfuscation, &added("x.py", py.as_bytes()))[0].rule, "t13.decode-exec");
        let js = "const s = Buffer.from(p, 'base64').toString();\nnew Function(s)();\n";
        assert_eq!(scan(&Obfuscation, &added("x.js", js.as_bytes()))[0].rule, "t13.decode-exec");
        assert!(scan(&Obfuscation, &added("x.js", b"const d = atob(token);\nconsole.log(d);\n")).is_empty());
        // Only added lines count.
        assert!(scan(&Obfuscation, &modified("x.py", py.as_bytes(), format!("{py}print(2)\n").as_bytes())).is_empty());
        // Out of scope: minified / vendored / non-source.
        assert!(scan(&Obfuscation, &added("dist/x.js", py.as_bytes())).is_empty());
        assert!(scan(&Obfuscation, &added("lib/x.min.js", py.as_bytes())).is_empty());
    }

    #[test]
    fn long_lines_and_entropy() {
        let long = format!("const a = [{}];\n", "1,".repeat(3000));
        assert_eq!(scan(&Obfuscation, &added("a.ts", long.as_bytes()))[0].rule, "t13.long-line");
        let mut seed: u64 = 42;
        let alphabet = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        let blob: String = (0..300)
            .map(|_| {
                seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
                alphabet[(seed >> 33) as usize % 64] as char
            })
            .collect();
        let js = format!("const k = \"{blob}\";\n");
        assert_eq!(scan(&Obfuscation, &added("k.js", js.as_bytes()))[0].rule, "t13.high-entropy");
        let generated_js = format!("// @generated by protoc\nconst k = \"{blob}\";\n");
        assert!(scan(&Obfuscation, &added("k.js", generated_js.as_bytes())).is_empty());
    }

    #[test]
    fn wiring() {
        let mut runner =
            Finding::new(Threat::T5, "t5.npm.script", Severity::Medium, "postinstall").path("web/package.json");
        runner.refs = vec!["scripts/setup.js".into()];
        let target =
            Finding::new(Threat::T13, "t13.decode-exec", Severity::High, "decodes").path("web/scripts/setup.js");
        let mut out = vec![runner, target];
        PayloadWired.scan_context(&ScanContext::default(), &mut out);
        let w = out.iter().find(|f| f.rule == "t13.payload-wired").expect("wired");
        assert_eq!(w.severity, Severity::Critical);
        assert_eq!(w.path.as_deref(), Some("web/scripts/setup.js"));
    }
}
